#!/usr/bin/env python3
"""Make a pg_dump schema readable without making it untrue.

pg_dump emits each COMMENT ON as one very long line after its CREATE
TABLE. The text is right there but nobody reads a 400-character line,
so the descriptions may as well not exist.

This moves them: a wrapped `--` banner above each table, listing the
table's own description and any column notes, with the executable
COMMENT ON statements collected at the end so restoring the file still
reproduces them in the database. Comments are never edited here --
they come from the migration, so the database stays the source of
truth and this file cannot drift from it.
"""
from __future__ import annotations

import re
import sys
import textwrap

TABLE_RE = re.compile(r"^COMMENT ON TABLE public\.(\w+) IS '(.*)';\s*$")
COLUMN_RE = re.compile(r"^COMMENT ON COLUMN public\.(\w+)\.(\w+) IS '(.*)';\s*$")
CREATE_RE = re.compile(r"^CREATE TABLE public\.(\w+) \(")
# pg_dump labels every object with a "-- Name: ..." line; the ones
# introducing a COMMENT become noise once the text is hoisted away.
NAME_COMMENT_RE = re.compile(r"^-- Name: .*; Type: COMMENT;")
WIDTH = 72


def unquote(s: str) -> str:
    return s.replace("''", "'")


def banner(table: str, desc: str, cols: dict[str, str]) -> list[str]:
    out = ["--" + "=" * WIDTH, f"-- {table}", "--" + "=" * WIDTH]
    for line in textwrap.wrap(desc, WIDTH) or [""]:
        out.append(f"-- {line}")
    for col, text in cols.items():
        out.append("--")
        pad = " " * (len(col) + 2)
        wrapped = textwrap.wrap(text, WIDTH - len(col) - 2) or [""]
        out.append(f"--   {col}: {wrapped[0]}")
        out.extend(f"--   {pad}{line}" for line in wrapped[1:])
    out.append("")
    return out


def main() -> int:
    lines = sys.stdin.read().split("\n")

    table_desc: dict[str, str] = {}
    col_desc: dict[str, dict[str, str]] = {}
    statements: list[str] = []
    kept: list[str] = []

    for line in lines:
        m = TABLE_RE.match(line)
        if m:
            table_desc[m.group(1)] = unquote(m.group(2))
            statements.append(line.strip())
            continue
        m = COLUMN_RE.match(line)
        if m:
            col_desc.setdefault(m.group(1), {})[m.group(2)] = unquote(m.group(3))
            statements.append(line.strip())
            continue
        if NAME_COMMENT_RE.match(line):
            continue
        kept.append(line)

    out: list[str] = []
    for line in kept:
        m = CREATE_RE.match(line)
        if m and m.group(1) in table_desc:
            t = m.group(1)
            # Drop pg_dump's own "-- Name: accounts; Type: TABLE" line
            # immediately above, which the banner replaces.
            while out and (out[-1].startswith("-- Name:") or not out[-1].strip()):
                out.pop()
            out.append("")
            out.extend(banner(t, table_desc[t], col_desc.get(t, {})))
        out.append(line)

    text = re.sub(r"\n{3,}", "\n\n", "\n".join(out))

    if statements:
        rule = "--" + "=" * WIDTH
        text += (
            f"\n\n{rule}\n"
            "-- The same descriptions, as statements, so restoring this file\n"
            "-- puts them back in the database. Edit them in a migration, not\n"
            "-- here: this file is regenerated by scripts/dump-schema.sh.\n"
            f"{rule}\n\n" + "\n\n".join(statements) + "\n"
        )
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
